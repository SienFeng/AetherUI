package ipdb

import "testing"

func TestCanonicalCityStripsAdministrativeSuffix(t *testing.T) {
	for _, c := range []struct{ in, want string }{
		// 两个源对同一个城市的两种写法，归一后必须相等。
		{"南京市", "南京"},
		{"南京", "南京"},
		{"聊城市", "聊城"},
		{"聊城", "聊城"},
		{"  杭州市  ", "杭州"},

		// 自治州：纯真库给简称、ip2region 给全称，民族名夹在中间，
		// 只剥「自治州」剩下的是「伊犁哈萨克」而不是「伊犁」。
		{"伊犁哈萨克自治州", "伊犁"},
		{"伊犁", "伊犁"},
		{"昌吉回族自治州", "昌吉"},
		{"大理白族自治州", "大理"},
		{"博尔塔拉蒙古自治州", "博尔塔拉"},
		{"巴音郭楞蒙古自治州", "巴音郭楞"},
		{"克孜勒苏柯尔克孜自治州", "克孜勒苏"},
		{"延边朝鲜族自治州", "延边"},
		{"恩施土家族苗族自治州", "恩施"},
		{"海西蒙古族藏族自治州", "海西"},
		{"红河哈尼族彝族自治州", "红河"},
		{"德宏傣族景颇族自治州", "德宏"},
		{"黔东南苗族侗族自治州", "黔东南"},
		{"阿坝藏族羌族自治州", "阿坝"},
		{"怒江傈僳族自治州", "怒江"},
		{"文山壮族苗族自治州", "文山"},
		{"西双版纳傣族自治州", "西双版纳"},
		{"临夏回族自治州", "临夏"},

		// 其余地级建制。
		{"阿里地区", "阿里"},
		{"阿拉善盟", "阿拉善"},
		{"香港特别行政区", "香港"},

		// 后缀就是整个名字时不能剥成空串。
		{"市", "市"},
		{"", ""},
	} {
		if got := CanonicalCity(c.in); got != c.want {
			t.Errorf("CanonicalCity(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}

// 归一不能把两个真的不同的城市合成一个——那会让「存疑」漏报，
// 比它现在的误报严重：管理员看到的是一个被当成唯一答案的错误归属地。
func TestCanonicalCityKeepsDistinctCitiesDistinct(t *testing.T) {
	for _, c := range [][2]string{
		{"南京市", "扬州市"},
		{"济南市", "临沂"},
		{"呼伦贝尔市", "赤峰"},
		{"大理白族自治州", "丽江市"},
	} {
		if CanonicalCity(c[0]) == CanonicalCity(c[1]) {
			t.Errorf("CanonicalCity 把 %q 与 %q 归成了同一个城市", c[0], c[1])
		}
	}
}
